-- A second database on the same server, useful for testing :connect and
-- connection switching without leaving PostgreSQL.
CREATE DATABASE analytics;

\connect analytics

CREATE TABLE events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL,
  payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

